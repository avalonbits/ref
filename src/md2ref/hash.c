/*
 * Pearson's hash: a byte at a time through a table that shuffles the 256
 * byte values, h = table[h ^ byte]. An 8-bit lookup and an exclusive or
 * are what the eZ80 does in line, where FNV's multiply is a 32-bit call
 * for every byte. Two lanes, started apart, make 16 bits.
 */

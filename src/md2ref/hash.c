unsigned md_hash(unsigned seed, const char* s, unsigned n)
{
    const uint8_t* p = (const uint8_t*)s;
    const uint8_t* e = p + n;
    uint8_t a = md_pearson[(uint8_t)seed];
    uint8_t b = md_pearson[(uint8_t)(seed + 1)];

    while (p < e) {
        a = md_pearson[a ^ *p];
        b = md_pearson[b ^ *p++];
    }

    return (unsigned)b << 8 | a;
}
